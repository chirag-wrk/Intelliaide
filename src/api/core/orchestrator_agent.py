    def _call_claude_with_tools(
        self,
        system_prompt: str,
        messages: List[Dict],
        tool_definitions: List[Dict],
    ) -> Dict[str, Any]:
        """
        Call Claude Messages API with tool_use support.

        This is the orchestrator's OWN Claude API code, separate from the
        LLM code in must_gather_file_selector.py and llm_rca_agent.py.
        Those modules make plain-text calls; this one uses tool_use so Claude
        can pick tools and drive the ReAct loop.

        Returns
        -------
        {
            "stop_reason": "end_turn" | "tool_use",
            "content":  list   — full content blocks from Claude response
            "tool_use_blocks": list — extracted tool_use blocks
            "text_blocks": list — extracted text blocks (Claude's reasoning)
            "usage": {"input_tokens": int, "output_tokens": int}
        }
        """
        if not REQUESTS_AVAILABLE:
            raise RuntimeError("requests package not available — cannot call Claude API")

        config = load_llm_config(self.config_path)
        claude_config = config.get("claude", {})
        max_tokens = claude_config.get("max_tokens", 16384)
        verify_ssl = claude_config.get("verify_ssl", True)
        is_custom_gateway = claude_config.get("custom_gateway", False)

        # ── GCP Vertex AI endpoint & gcloud token auth ──
        api_token = resolve_api_token(claude_config)
        api_endpoint = resolve_api_endpoint(claude_config)

        if not api_token:
            raise RuntimeError(
                "No API token available. Check auth_type/api_key in config.json "
                "or the ANTHROPIC_API_KEY environment variable."
            )

        # OLD VERSION — Red Hat custom gateway / direct Anthropic endpoint (no longer active):
        # api_key = claude_config.get("api_key") or os.getenv("ANTHROPIC_API_KEY")
        # api_url = (claude_config.get("api_url", "https://api.anthropic.com")).rstrip("/")
        # is_custom_gateway = "api.anthropic.com" not in api_url
        # if is_custom_gateway:
        #     api_endpoint = f"{api_url}/sonnet/models/{model_id}:streamRawPredict"
        # else:
        #     api_endpoint = f"{api_url}/v1/messages"

        # --- Build request ---
        if is_custom_gateway:
            payload = {
                "anthropic_version": "vertex-2023-10-16",
                "system": system_prompt,
                "messages": messages,
                "tools": tool_definitions,
                "max_tokens": max_tokens,
                "temperature": 0,
            }
        else:
            model_id = claude_config.get("model_id", "claude-sonnet-4-6")
            payload = {
                "model": model_id,
                "system": system_prompt,
                "messages": messages,
                "tools": tool_definitions,
                "max_tokens": max_tokens,
            }

        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_token}",
        }
        if not is_custom_gateway:
            headers["anthropic-version"] = "2023-06-01"

        # --- Call ---
        response = requests.post(
            api_endpoint,
            headers=headers,
            json=payload,
            verify=verify_ssl,
            timeout=300,
        )
        response.raise_for_status()
        resp_json = response.json()

        # --- Parse response ---
        stop_reason = resp_json.get("stop_reason", "end_turn")
        content = resp_json.get("content", [])
        usage = resp_json.get("usage", {})

        tool_use_blocks = []
        text_blocks = []
        for block in (content if isinstance(content, list) else []):
            if isinstance(block, dict):
                if block.get("type") == "tool_use":
                    tool_use_blocks.append(block)
                elif block.get("type") == "text":
                    text_blocks.append(block)

        return {
            "stop_reason": stop_reason,
            "content": content,
            "tool_use_blocks": tool_use_blocks,
            "text_blocks": text_blocks,
            "usage": {
                "input_tokens": usage.get("input_tokens", 0),
                "output_tokens": usage.get("output_tokens", 0),
            },
        }

