    def _emit_pre_tool_progress(self, tool_name: str, progress_callback):
        """Fire progress_callback BEFORE a tool executes (phase headers)."""
        if not progress_callback:
            return

        if tool_name == "select_files":
            progress_callback("terminal_block", "", {
                "lines": ["=" * 80,
                           "Phase 1: Selecting the Probable and available files for Issue analysis",
                           "=" * 80]
            })
            progress_callback(
                "files_identified_intent",
                "Intent: Use LLM to analyze your input and identify priority must-gather files for analysis.",
                None,
            )

        elif tool_name == "analyze_yaml":
            stage = "high"  # will be refined in post-tool
            progress_callback("terminal_block", "", {
                "lines": ["=" * 80,
                           f"Phase 2: Selected YAML files processing ({stage} priority)",
                           "=" * 80]
            })

        elif tool_name == "perform_rca":
            # Only signal data_aggregation here — the phase stays here for the entire
            # payload-building + chunk-processing work inside perform_rca.
            # rca_analysis is emitted in _emit_post_tool_progress once perform_rca returns.
            progress_callback("phase4_aggregation",
                              "Phase 4: Relevant data aggregation from YAML and LOG files", None)
            progress_callback("terminal_block", "", {
                "lines": ["=" * 80, "Phase 4: Aggregating YAML and log data for RCA payload", "=" * 80]
            })

    def _emit_post_tool_progress(self, tool_name: str, tool_result: Dict,
                                 agent_state: Dict, progress_callback):
        """Fire progress_callback AFTER a tool executes (result summaries)."""
        if not progress_callback:
            return

        data = tool_result.get("data", {})
        success = tool_result.get("success", False)

        if tool_name == "select_files" and success:
            suggested = data.get("suggested_files", [])
            all_paths = [f.get("path", "") for f in suggested]
            progress_callback("file_selection_llm_result", "Files selected for analysis.", {
                "used_llm": True,
                "reasoning": data.get("reasoning", ""),
                "problem_category": data.get("problem_category", "Unknown"),
                "files": all_paths,
            })
            progress_callback("files_identified",
                              "Shortlisted files for analysis based on the user presented issue",
                              {"files": all_paths})
            # Priority breakdown
            fbp = agent_state.get("files_by_priority", {})
            stage = agent_state.get("rca_priority_stage", "high")
            progress_callback("files_by_priority",
                              f"Files by priority (first run uses {stage} only)", {
                                  "high": fbp.get("high", []),
                                  "medium": fbp.get("medium", []),
                                  "low": fbp.get("low", []),
                                  "first_run_paths": fbp.get("high", []),
                                  "rca_priority_stage": stage,
                              })

        elif tool_name == "check_file_availability" and success:
            progress_callback("files_availability",
                              "Shortlisted files: availability in must-gather directory",
                              data)

        elif tool_name == "analyze_yaml" and success:
            # data_analyzer fires yaml_processing, classification, etc. internally
            # via the progress_callback passed through context — we only fire the
            # summary callback here.
            progress_callback("data_analysis_done", "YAML processing complete", {
                "classification_table": data.get("classification_table"),
                "total_yaml_bytes": data.get("total_yaml_bytes", 0),
                "summary": {
                    "files_processed": data.get("files_processed", 0),
                    "critical_fields_extracted": data.get("total_objects", 0),
                },
                "files_with_no_output": data.get("files_with_no_output", []),
            })

        # analyze_logs: data_analyzer fires phase3_logs_start, log_processing_result
        # internally via progress_callback in context — nothing extra needed here.

        elif tool_name == "perform_rca":
            # perform_rca has finished (payload built + all chunks processed).
            # Now transition the UI from data_aggregation → rca_analysis so the
            # "Root Cause Analysis" step lights up while the orchestrator synthesises
            # the final report.  llm_done is emitted later in _build_final_report.
            progress_callback("terminal_block", "", {
                "lines": ["=" * 80, "Phase 5: Root Cause analysis — synthesising findings", "=" * 80]
            })
            progress_callback(
                "llm_start_intent",
                "Intent: Synthesise YAML + log findings into the final RCA report.",
                None,
            )
            progress_callback("llm_start", "Building final RCA report...", None)

    def _generate_causal_dag_after_rca(
        self,
        rca_text: str,
        problem_statement: str,
        priority_stage: str,
        progress_callback=None,
        *,
        quiet: bool | None = None,
    ) -> Dict:
        """Orchestrator-only post-RCA causal DAG generation (not an agent tool call)."""
        if quiet is None:
            quiet = self._load_quiet()
        if progress_callback:
            progress_callback("terminal_block", "", {
                "lines": ["=" * 80, "Phase 5b: Generating causal DAG for UI diagram", "=" * 80]
            })
            progress_callback(
                "llm_start_intent",
                "Intent: Distil the RCA report into a structured causal DAG (JSON).",
                None,
            )
            progress_callback("llm_start", "Generating causal DAG...", None)
        if not quiet:
            print("[Orchestrator] Generating causal DAG (post-RCA)...")
        try:
            return execute_generate_causal_dag(
                {"priority_stage": priority_stage},
                {
                    "config_path": self.config_path,
                    "agent_state": {
                        "rca_text": rca_text,
                        "problem_statement": problem_statement,
                        "rca_priority_stage": priority_stage,
                    },
                },
            )
        except Exception as exc:
            if not quiet:
                print(f"[Orchestrator] Warning: Could not generate causal DAG: {exc}")
            return {"success": False, "data": {}, "summary": str(exc)}

