    # ------------------------------------------------------------------

    def _store_tool_result(self, session_id: str, tool_name: str,
                           tool_result: Dict, agent_state: Dict):
        """
        Store tool result in agent_memory.json session and update the
        accumulating agent_state dict.
        """
        session = self.get_session(session_id)
        if not session:
            return

        data = tool_result.get("data", {})
        success = tool_result.get("success", False)

        # Audit trail
        session['sub_agent_calls'].append({
            'agent': tool_name,
            'timestamp': datetime.datetime.now().isoformat(),
            'success': success,
            'summary': tool_result.get("summary", "")[:500],
        })

        # ----- select_files -----
        if tool_name == "select_files" and success:
            session["results"]["file_suggestions"] = data
            session["status"] = "file_selection_completed"

            # Parse priorities, normalize paths, redistribute if needed
            suggested = data.get("suggested_files", [])
            by_pri: Dict[str, List[str]] = {"high": [], "medium": [], "low": []}
            for f in suggested:
                pri = f.get("priority", "medium").lower()
                path = f.get("path", "").strip()
                if pri in by_pri:
                    by_pri[pri].append(path)
                else:
                    by_pri["medium"].append(path)
            by_pri = self._redistribute_priorities(by_pri)
            agent_state["files_by_priority"] = by_pri

            agent_state["file_selection_input_tokens"] = data.get("input_tokens", 0)
            agent_state["file_selection_output_tokens"] = data.get("output_tokens", 0)
            self._track_workflow_step("file_selection", "completed", {
                "files_count": len(suggested),
                "priority_breakdown": {k: len(v) for k, v in by_pri.items()},
            })

            # select_files now auto-includes file availability — extract it here
            fa = data.get("file_availability")
            if fa:
                found = [
                    item.get("resolved", "")
                    for item in fa.get("found_in_supplied_dir", [])
                ]
                agent_state["files_available"] = found
                agent_state["files_not_found"] = fa.get("not_found", [])

                # Build resolved-path list per priority tier so tool executors can
                # batch ALL high-priority files of a given type in one call instead
                # of letting Claude split them across multiple ReAct iterations.
                _path_to_pri: Dict[str, str] = {}
                for _pri, _raw_list in by_pri.items():
                    for _rp in _raw_list:
                        _path_to_pri[_rp] = _pri
                _by_pri_resolved: Dict[str, List[str]] = {"high": [], "medium": [], "low": []}
                for _item in fa.get("found_in_supplied_dir", []):
                    _orig = _item.get("original", "")
                    _resolved = _item.get("resolved", "")
                    if not _resolved:
                        continue
                    _pri = _path_to_pri.get(_orig, "medium")
                    if _pri in _by_pri_resolved:
                        _by_pri_resolved[_pri].append(_resolved)
                agent_state["files_available_by_priority"] = _by_pri_resolved

        # ----- check_file_availability (standalone, for re-checks) -----
        elif tool_name == "check_file_availability" and success:
            found = [
                item.get("resolved", "")
                for item in data.get("found_in_supplied_dir", [])
            ]
            agent_state["files_available"] = found
            agent_state["files_not_found"] = data.get("not_found", [])

        # ----- analyze_yaml -----
        elif tool_name == "analyze_yaml" and success:
            # ml_classification_result is {"output_flags": {...}, "files": {fname: {objects, summary}}}
            # We only accumulate the "files" dict as YAML errors for RCA.
            raw_ml = data.get("ml_classification_result", {})
            ml = raw_ml.get("files", {}) if isinstance(raw_ml, dict) and "files" in raw_ml else raw_ml
            agent_state["accumulated_yaml_errors"].update(ml)
            agent_state["total_yaml_bytes"] += data.get("total_yaml_bytes", 0)
            agent_state["yaml_file_sizes"].update(data.get("yaml_file_sizes", {}))
            new_files = data.get("analyzed_files", [])
            agent_state["files_analyzed"].extend(new_files)
            self._update_analyzed_tiers(agent_state, new_files)

            # Accumulate classification table across multiple analyze_yaml calls
            new_table = data.get("classification_table") or []
            if "accumulated_classification_table" not in agent_state:
                agent_state["accumulated_classification_table"] = []
            agent_state["accumulated_classification_table"].extend(new_table)

            # Persist cumulative results for continue_rca_with_feedback
            session["results"]["ml_classification_result"] = dict(agent_state["accumulated_yaml_errors"])
            if "data_analysis" not in session["results"]:
                session["results"]["data_analysis"] = {}
            session["results"]["data_analysis"]["classification_table"] = list(agent_state["accumulated_classification_table"])
            session["results"]["data_analysis"]["yaml_file_sizes"] = dict(agent_state["yaml_file_sizes"])
            session["results"]["data_analysis"]["total_yaml_bytes"] = agent_state["total_yaml_bytes"]
            session["results"]["data_analysis"].update({
                k: v for k, v in data.items()
                if k not in ("classification_table", "yaml_file_sizes", "total_yaml_bytes", "ml_classification_result")
            })
            session["status"] = "data_analysis_completed"
            self._track_workflow_step("data_analysis", "completed", {
                "files_count": len(new_files),
            })

        # ----- analyze_json -----
        elif tool_name == "analyze_json" and success:
            # JSON errors merge into accumulated_yaml_errors (same dict, keyed by filename)
            # so validate_token_budget and perform_rca see them automatically.
            raw_ml = data.get("ml_classification_result", {})
            ml = raw_ml.get("files", {}) if isinstance(raw_ml, dict) and "files" in raw_ml else raw_ml
            agent_state["accumulated_yaml_errors"].update(ml)
            new_files = data.get("analyzed_files", [])
            agent_state["files_analyzed"].extend(new_files)
            self._update_analyzed_tiers(agent_state, new_files)

            new_table = data.get("classification_table") or []
            if "accumulated_classification_table" not in agent_state:
                agent_state["accumulated_classification_table"] = []
            agent_state["accumulated_classification_table"].extend(new_table)

            session["results"]["ml_classification_result"] = dict(agent_state["accumulated_yaml_errors"])
            if "data_analysis" not in session["results"]:
                session["results"]["data_analysis"] = {}
            session["results"]["data_analysis"]["classification_table"] = list(agent_state["accumulated_classification_table"])
            session["status"] = "data_analysis_completed"
            self._track_workflow_step("json_analysis", "completed", {
                "files_count": len(new_files),
            })

        # ----- analyze_logs -----
        elif tool_name == "analyze_logs" and success:
            new_entries = data.get("log_error_entries", [])
            existing_files = {e.get("file") for e in agent_state["accumulated_log_entries"]}
            agent_state["accumulated_log_entries"].extend(
                e for e in new_entries if e.get("file") not in existing_files
            )
            agent_state["total_log_bytes"] += data.get("total_log_bytes", 0)
            new_files = data.get("analyzed_files", [])
            agent_state["files_analyzed"].extend(new_files)
            self._update_analyzed_tiers(agent_state, new_files)

            session["results"]["log_error_entries"] = list(agent_state["accumulated_log_entries"])
            session["results"]["total_log_bytes"] = agent_state["total_log_bytes"]

        # ----- perform_rca -----
        elif tool_name == "perform_rca":
            rca_text = data.get("rca_summary", "")
            is_error = rca_text.startswith("Error:") or rca_text.startswith("Claude API error:")
            new_tokens_in = data.get("input_tokens", 0)
            new_tokens_out = data.get("output_tokens", 0)
            new_cost = data.get("cost_usd", 0.0)
            new_payload = data.get("payload_bytes", 0)

            agent_state["rca_input_tokens"] += new_tokens_in
            agent_state["rca_output_tokens"] += new_tokens_out
            agent_state["rca_cost_usd"] += new_cost
            agent_state["rca_payload_bytes"] += new_payload

            if rca_text and not is_error:
                agent_state["rca_text"] = rca_text

            session["results"]["rca_result"] = {
                "input_tokens": agent_state["rca_input_tokens"],
                "output_tokens": agent_state["rca_output_tokens"],
                "cost_usd": agent_state["rca_cost_usd"],
                "payload_bytes": agent_state["rca_payload_bytes"],
            }

        self.update_session(session_id, {})

    # ==================================================================
    #  execute_workflow — The ReAct Agent Loop
    # ==================================================================

    def execute_workflow(
        self,
        problem_statement: str,
        must_gather_docs_dir: str,
        must_gather_base_dir: str = None,
        progress_callback=None,
        output_session_id: str = None,
    ) -> Dict:
        """
        Execute the agentic ReAct workflow.

        Claude reasons about what tool to call next, executes tools, observes
        results, and decides when to return a final RCA report.

        Contract with chat_ui.py is preserved:
          - Same parameters
          - Same return dict shape  (session_id, status, need_rca_feedback,
            rca_summary, rca_priority_stage, has_more_priorities, …)
          - Same progress_callback step names
        """
        session_id = self.create_session(problem_statement)
        if output_session_id:
            self.update_session(session_id, {"api_session_id": output_session_id})
        quiet = self._load_quiet()

        # ── Tee all console output to Results/workflow_console.txt ──
        log_file = None
        original_stdout = sys.stdout
        try:
            log_path = get_results_dir() / "workflow_console.txt"
            log_file = open(log_path, "w", encoding="utf-8")
            sys.stdout = _TeeWriter(log_file, original_stdout)
        except Exception as e:
            print(f"[Orchestrator] Warning: Could not open workflow log: {e}")

        # Accumulating agent state —  persisted into session at the end
        agent_state: Dict[str, Any] = {
            "problem_statement": problem_statement,
            "files_by_priority": {"high": [], "medium": [], "low": []},
            "files_available": [],
            "files_not_found": [],
            "accumulated_yaml_errors": {},
            "accumulated_log_entries": [],
            "files_analyzed": [],
            "total_yaml_bytes": 0,
            "total_log_bytes": 0,
            "yaml_file_sizes": {},
            "rca_text": "",
            "rca_input_tokens": 0,
            "rca_output_tokens": 0,
            "rca_cost_usd": 0.0,
            "rca_payload_bytes": 0,
            "rca_priority_stage": "high",
            "file_selection_input_tokens": 0,
            "file_selection_output_tokens": 0,
            "deepening_rounds": [],
            "reasoning_trace": [],
            "iteration_count": 0,
            "cumulative_input_tokens": 0,
            "cumulative_output_tokens": 0,
        }

        # Build tool-execution context
        # agent_state is shared so tools like perform_rca and validate_token_budget
        # can auto-read accumulated YAML errors / log entries without Claude passing them.
        context: Dict[str, Any] = {
            "must_gather_selector": self.must_gather_selector,
            "data_analyzer": self.data_analyzer,
            "config_path": self.config_path,
            "must_gather_base_dir": must_gather_base_dir or "",
            "must_gather_docs_dir": must_gather_docs_dir,
            "progress_callback": progress_callback,
            "agent_state": agent_state,
        }
        self._last_must_gather_docs_dir = must_gather_docs_dir
        if must_gather_base_dir and self.data_analyzer:
            self.data_analyzer.must_gather_base_dir = must_gather_base_dir

        # Build system prompt and first user message
        system_prompt = build_system_prompt(max_iterations=self.max_iterations)
        user_msg = build_user_message(
            problem_statement, must_gather_docs_dir, must_gather_base_dir or "",
        )
        messages: List[Dict[str, Any]] = [{"role": "user", "content": user_msg}]

        if not quiet:
            print("\n" + "=" * 100)
            print("AGENTIC ORCHESTRATOR — ReAct Loop")
            print("=" * 100)
            print(f"Problem: {problem_statement[:200]}")
            print(f"Max iterations: {self.max_iterations}")

        # Track tools that have already failed — never re-execute a failed tool
        failed_tools: set = set()
        # Tools that must run at most once per workflow (even on success)
        _ONCE_ONLY_TOOLS = {"perform_rca", "select_files"}
        _dag_generated = False
        completed_once_only: set = set()
        # Flag to force-exit the loop (set on critical/unrecoverable errors)
        _force_exit = False
        _force_exit_reason = ""

        try:
            iteration = 0
            while iteration < self.max_iterations:
                iteration += 1
                agent_state["iteration_count"] = iteration

                if _force_exit:
                    if not quiet:
                        print(f"\n[Agent] Force-exiting loop: {_force_exit_reason}")
                    break

                if not quiet:
                    print(f"\n--- Agent iteration {iteration}/{self.max_iterations} ---")

                # Mandatory causal-DAG step after perform_rca — orchestrator-driven only.
                if (
                    agent_state.get("rca_text")
                    and "perform_rca" in completed_once_only
                    and not _dag_generated
                ):
                    priority_stage = agent_state.get("rca_priority_stage", "high")
                    dag_result = self._generate_causal_dag_after_rca(
                        agent_state["rca_text"],
                        agent_state.get("problem_statement", ""),
                        priority_stage,
                        progress_callback,
                        quiet=quiet,
                    )
                    _dag_generated = True
                    if dag_result.get("success"):
                        agent_state["causal_dag_generated"] = True
                        agent_state["causal_dag_path"] = dag_result.get("data", {}).get("dag_path", "")
                    if not quiet:
                        print(
                            f"  [Auto-step result] success={dag_result.get('success')}, "
                            f"summary={(dag_result.get('summary') or '')[:200]}"
                        )
                    continue

                # Small delay between iterations to avoid rate-limiting
                if iteration > 1:
                    import time as _time
                    _time.sleep(5)

                # ── THINK + DECIDE ──────────────────────────────────────
                try:
                    response = self._call_claude_with_tools(
                        system_prompt, messages, ORCHESTRATOR_TOOL_DEFINITIONS,
                    )
                except Exception as e:
                    if not quiet:
                        print(f"\n[Agent] LLM API call failed: {e}")
                        traceback.print_exc()
                    _force_exit = True
                    _force_exit_reason = f"LLM API call failed: {e}"
                    break

                # Track token usage
                usage = response.get("usage", {})
                agent_state["cumulative_input_tokens"] += usage.get("input_tokens", 0)
                agent_state["cumulative_output_tokens"] += usage.get("output_tokens", 0)

                # Log Claude's reasoning (text blocks)
                for tb in response.get("text_blocks", []):
                    text = tb.get("text", "").strip()
                    if text:
                        agent_state["reasoning_trace"].append(text[:500])
                        if not quiet:
                            preview = text[:300] + ("..." if len(text) > 300 else "")
                            print(f"  [Agent thinks]: {preview}")

                stop_reason = response.get("stop_reason", "end_turn")

                # ── FINAL ANSWER ────────────────────────────────────────
                if stop_reason == "end_turn":
                    if not quiet:
                        print("\n  [Agent] Returning final answer.")
                    return self._build_final_report(
                        response, session_id, agent_state, context, progress_callback,
                    )

                # ── TOOL USE ────────────────────────────────────────────
                tool_blocks = response.get("tool_use_blocks", [])
                if not tool_blocks:
                    return self._build_final_report(
                        response, session_id, agent_state, context, progress_callback,
                    )

                # Append assistant message with full content (required for Claude API)
                messages.append({"role": "assistant", "content": response["content"]})

                # Execute each tool Claude requested
                tool_results_content: List[Dict[str, Any]] = []
                tools_this_turn: set = set()
                for tb in tool_blocks:
                    tool_name = tb.get("name", "")
                    tool_id = tb.get("id", "")
                    tool_input = tb.get("input", {})

                    if not quiet:
                        input_preview = json.dumps(tool_input, default=str)[:200]
                        print(f"  [Tool call] {tool_name}({input_preview})")

                    # Block re-execution of tools that have already failed
                    if tool_name in failed_tools:
                        result = {
                            "success": False,
                            "data": {},
                            "summary": (
                                f"BLOCKED: Tool '{tool_name}' already failed in a previous "
                                f"iteration. Do NOT retry failed tools — proceed with "
                                f"available data or return the final report."
                            ),
                        }
                        if not quiet:
                            print(f"  [BLOCKED] {tool_name} already failed — skipping re-execution")
                    elif tool_name in completed_once_only:
                        result = {
                            "success": True,
                            "data": {},
                            "summary": (
                                f"ALREADY COMPLETED: Tool '{tool_name}' already ran successfully. "
                                f"It must not run twice in the same workflow. "
                                f"Proceed to the FINAL REPORT now."
                            ),
                        }
                        if not quiet:
                            print(f"  [SKIPPED] {tool_name} already completed — once-only tool")
                    else:
                        # Execute via dispatch map from tools.py
                        executor = TOOL_EXECUTORS.get(tool_name)
                        if not executor:
                            result = {
                                "success": False,
                                "data": {},
                                "summary": f"Unknown tool: {tool_name}",
                            }
                        else:
                            try:
                                self._emit_pre_tool_progress(tool_name, progress_callback)
                                result = executor(tool_input, context)
                            except Exception as e:
                                failed_tools.add(tool_name)
                                if not quiet:
                                    print(f"  [EXCEPTION] Tool '{tool_name}' threw: {e}")
                                    traceback.print_exc()
                                result = {
                                    "success": False,
                                    "data": {"error": str(e), "traceback": traceback.format_exc()},
                                    "summary": f"Tool execution EXCEPTION: {e}. This tool will NOT be retried.",
                                }
                                _force_exit = True
                                _force_exit_reason = f"Tool '{tool_name}' threw an exception: {e}"

                        # Track tools that return success=false (prevent retries)
                        if not result.get("success", False):
                            failed_tools.add(tool_name)
                        if tool_name in _ONCE_ONLY_TOOLS and result.get("success", False):
                            completed_once_only.add(tool_name)

                    tools_this_turn.add(tool_name)

                    if not quiet:
                        summary_preview = result.get("summary", "")[:200]
                        print(f"  [Tool result] success={result.get('success')}, "
                              f"summary={summary_preview}")

                    # Fire post-tool progress callbacks (chat_ui.py display)
                    self._emit_post_tool_progress(
                        tool_name, result, agent_state, progress_callback,
                    )

                    # Store in session memory and update agent state
                    self._store_tool_result(session_id, tool_name, result, agent_state)

                    # Collect tool result for the conversation
                    tool_results_content.append({
                        "type": "tool_result",
                        "tool_use_id": tool_id,
                        "content": result.get("summary", "No summary available."),
                    })

                # ── OBSERVE ─── (feed tool results back into conversation)
                messages.append({"role": "user", "content": tool_results_content})

            # ── Max iterations exhausted — graceful exit ────────────────
            if not quiet:
                print(f"\n[Agent] Max iterations ({self.max_iterations}) reached. "
                      "Returning partial results.")
            return self._build_graceful_exit(
                session_id, agent_state, context, progress_callback,
            )

        except Exception as e:
            error_msg = f"Error in agentic workflow: {str(e)}"
            if not quiet:
                print(f"[Orchestrator] {error_msg}")
                traceback.print_exc()
            self.status = AgentStatus.ERROR
            self._track_workflow_step('workflow', 'error', {'error': str(e)})
            self.update_session(session_id, {'status': 'error', 'error': error_msg})
            return {
                'session_id': session_id,
                'status': 'error',
                'error': error_msg,
                'timestamp': datetime.datetime.now().isoformat(),
            }

        finally:
            # ── Restore stdout and close log file ──
            sys.stdout = original_stdout
            if log_file:
                try:
                    log_file.close()
                    print(f"[Orchestrator] Full console log saved to: {get_results_dir() / 'workflow_console.txt'}")
                except Exception:
                    pass

    # ------------------------------------------------------------------
    # Final report builders
    # ------------------------------------------------------------------

    def _build_final_report(
        self,
        response: Dict,
        session_id: str,
        agent_state: Dict,
        context: Dict,
        progress_callback,
    ) -> Dict:
        """
        Extract the RCA from Claude's end_turn response, persist session state,
        emit the final progress callbacks, write rca_summary.txt, and return
        the result dict that chat_ui.py expects.
        """
        # --- Extract RCA text from Claude's final answer ---
        final_text = ""
        for block in response.get("text_blocks", []):
            final_text += block.get("text", "")
        if not final_text.strip():
            for block in (response.get("content") or []):
                if isinstance(block, dict) and block.get("type") == "text":
                    final_text += block.get("text", "")

        final_text_clean = (final_text or "").strip()
        fallback_text = (agent_state.get("rca_text") or "").strip()
        rca_text = final_text_clean or fallback_text

        # --- Build report_with_user_query (same format continue_rca expects) ---
        problem_statement = agent_state.get("problem_statement", "")
        user_query_block = (problem_statement or "").strip()

        report_with_user_query = ""
        if user_query_block:
            report_with_user_query = (
                "User Reported Issue:\n  "
                + user_query_block.replace("\n", "\n  ")
                + "\n\n" + "=" * 80 + "\n\n"
            )
        report_with_user_query += rca_text

        # --- Build cost table ---
        total_yaml_bytes = agent_state.get("total_yaml_bytes", 0)
        total_log_bytes = agent_state.get("total_log_bytes", 0)
        payload_bytes = agent_state.get("rca_payload_bytes", 0)

        # Per-file compression entries
        yaml_file_sizes = agent_state.get("yaml_file_sizes", {})
        accumulated_yaml = agent_state.get("accumulated_yaml_errors", {})
        log_entries = agent_state.get("accumulated_log_entries", [])
        compression_entries = []
        for file_name, objects in accumulated_yaml.items():
            orig = yaml_file_sizes.get(file_name, 0)
            pl = len(json.dumps(objects, default=str).encode("utf-8"))
            compression_entries.append({
                "file": file_name, "type": "yaml",
                "original_bytes": orig, "payload_bytes": pl,
            })
        for e in log_entries:
            orig = e.get("original_size", 0)
            pl = len((e.get("content") or "").encode("utf-8"))
            compression_entries.append({
                "file": e.get("file", ""), "type": "log",
                "original_bytes": orig, "payload_bytes": pl,
            })

        cost_table_str = self._build_llm_cost_table(
            agent_state.get("file_selection_input_tokens", 0),
            agent_state.get("file_selection_output_tokens", 0),
            agent_state.get("rca_input_tokens", 0),
            agent_state.get("rca_output_tokens", 0),
            agent_state.get("rca_cost_usd", 0.0),
            total_yaml_bytes,
            total_log_bytes=total_log_bytes,
            payload_bytes=payload_bytes,
            orchestrator_input_tokens=agent_state.get("cumulative_input_tokens", 0),
            orchestrator_output_tokens=agent_state.get("cumulative_output_tokens", 0),
            orchestrator_iterations=agent_state.get("iteration_count", 0),
            compression_entries=compression_entries if compression_entries else None,
        )

        # --- Emit final progress callbacks (chat_ui.py) ---
        if progress_callback and rca_text:
            progress_callback("llm_done", "RCA complete", {
                "rca_summary": rca_text,
                "report_with_user_query": report_with_user_query,
                "payload_bytes": payload_bytes,
                "total_yaml_bytes": total_yaml_bytes,
                "compression_explanation": (
                    "YAML errors (no line numbers) + log Error file contents "
                    "with metadata sent to the LLM."
                ),
                "cost_table": cost_table_str,
            })
        if progress_callback:
            progress_callback("phase6_cost", "Phase 6: Cost Calculation",
                              {"cost_table": cost_table_str})

        # --- Write RCA to file ---
        try:
            results_dir = get_results_dir()
            rca_doc_path = results_dir / "rca_summary.txt"

            # rca_priority_stage is stored in agent_state (set by _update_rca_priority_stage)
            rca_priority_stage_local = agent_state.get("rca_priority_stage", "high")
            stage_str = _STAGE_FILE_KEY.get(
                rca_priority_stage_local.split('_')[-1],
                "Tier1",
            )
            stage_doc_path = results_dir / f"RCA_{stage_str}.txt"

            # Master summary keeps the human-readable header for diagnostics
            master_content = "ROOT CAUSE ANALYSIS REPORT\n" + "=" * 80 + "\n\n"
            if user_query_block:
                master_content += "User Reported Issue:\n  " + user_query_block.replace("\n", "\n  ") + "\n\n" + "=" * 80 + "\n\n"
            master_content += rca_text + "\n" + cost_table_str + "\n"

            # Stage file contains clean markdown only (no === decorations) for the UI
            stage_content = rca_text + "\n\n" + cost_table_str + "\n"

            with open(rca_doc_path, 'w', encoding='utf-8') as f:
                f.write(master_content)
            with open(stage_doc_path, 'w', encoding='utf-8') as f:
                f.write(stage_content)

            if not self._load_quiet():
                print(f"\n[Orchestrator] Master RCA summary written to: {rca_doc_path.name}")
                print(f"[Orchestrator] Stage-specific RCA written to: {stage_doc_path.name}")

            # Generate a short executive summary for the RCA Report page
            try:
                exec_summary = generate_rca_pass_summary(
                    rca_text, problem_statement, self.config_path,
                )
                if exec_summary:
                    summary_path = results_dir / "rca_report_summary.txt"
                    summary_path.write_text(exec_summary, encoding="utf-8")
                    if not self._load_quiet():
                        print(f"[Orchestrator] RCA report summary written to: {summary_path.name}")
            except Exception as _se:
                print(f"[Orchestrator] Warning: Could not generate executive summary: {_se}")
        except Exception as e:
            print(f"[Orchestrator] Warning: Could not write rca_summary.txt or stage file: {e}")

        # Print cost table to console
        if not self._load_quiet():
            print(cost_table_str)

        # --- Determine has_more_priorities (for chat_ui feedback buttons) ---
        files_by_priority = agent_state.get("files_by_priority", {})
        rca_priority_stage = agent_state.get("rca_priority_stage", "all")

        has_more_priorities = False
        if files_by_priority:
            if rca_priority_stage == "high" and (
                files_by_priority.get("medium") or files_by_priority.get("low")
            ):
                has_more_priorities = True
            elif rca_priority_stage == "high_medium" and files_by_priority.get("low"):
                has_more_priorities = True

        # --- Persist in session (continue_rca_with_feedback reads these) ---
        session = self.get_session(session_id)
        if session:
            session["results"]["rca_summary"] = report_with_user_query
            session["results"]["rca_result"] = {
                "rca_summary": rca_text,
                "input_tokens": agent_state.get("rca_input_tokens", 0),
                "output_tokens": agent_state.get("rca_output_tokens", 0),
                "cost_usd": agent_state.get("rca_cost_usd", 0.0),
                "payload_bytes": agent_state.get("rca_payload_bytes", 0),
            }
            # Per-stage individual costs (not cumulative) — first pass is always Tier1
            session["results"]["rca_costs_per_stage"] = {
                "Tier1": {
                    "input_tokens": agent_state.get("rca_input_tokens", 0),
                    "output_tokens": agent_state.get("rca_output_tokens", 0),
                    "cost_usd": agent_state.get("rca_cost_usd", 0.0),
                    "payload_bytes": agent_state.get("rca_payload_bytes", 0),
                    "shortlisted_yaml_bytes": agent_state.get("total_yaml_bytes", 0),
                    "shortlisted_log_bytes": agent_state.get("total_log_bytes", 0),
                    "shortlisted_total_bytes": (
                        agent_state.get("total_yaml_bytes", 0)
                        + agent_state.get("total_log_bytes", 0)
                    ),
                    "orchestrator_input_tokens": agent_state.get("cumulative_input_tokens", 0),
                    "orchestrator_output_tokens": agent_state.get("cumulative_output_tokens", 0),
                    "orchestrator_cost_usd": 0.0,  # Set below once pricing is read
                    "file_selection_input_tokens": agent_state.get("file_selection_input_tokens", 0),
                    "file_selection_output_tokens": agent_state.get("file_selection_output_tokens", 0),
                    "file_selection_cost_usd": 0.0,  # Set below once pricing is read
                    # Internal snapshots for next-stage delta computation
                    "orchestrator_cum_input_tokens": agent_state.get("cumulative_input_tokens", 0),
                    "orchestrator_cum_output_tokens": agent_state.get("cumulative_output_tokens", 0),
                    "file_selection_cum_input_tokens": agent_state.get("file_selection_input_tokens", 0),
                    "file_selection_cum_output_tokens": agent_state.get("file_selection_output_tokens", 0),
                }
            }
            session["results"]["total_yaml_bytes"] = agent_state.get("total_yaml_bytes", 0)
            session["results"]["total_log_bytes"] = agent_state.get("total_log_bytes", 0)
            session["results"]["chronology"] = []  # Claude includes it in text
            session["results"]["rca_priority_stage"] = rca_priority_stage
            session["results"]["files_by_priority_paths"] = files_by_priority
            session["results"]["must_gather_base_dir"] = context.get("must_gather_base_dir", "")
            session["results"]["must_gather_docs_dir"] = context.get("must_gather_docs_dir", "")
            session["results"]["log_error_entries"] = agent_state.get("accumulated_log_entries", [])
            session["results"]["ml_classification_result"] = agent_state.get("accumulated_yaml_errors", {})
            session["results"]["deepening_rounds"] = agent_state.get("deepening_rounds", [])
            session["results"]["reasoning_trace"] = agent_state.get("reasoning_trace", [])
            session["results"]["agent_iteration_count"] = agent_state.get("iteration_count", 0)
            session["results"]["agent_input_tokens"] = agent_state.get("cumulative_input_tokens", 0)
            session["results"]["agent_output_tokens"] = agent_state.get("cumulative_output_tokens", 0)
            session["results"]["agent_total_tokens"] = (
                agent_state.get("cumulative_input_tokens", 0)
                + agent_state.get("cumulative_output_tokens", 0)
            )
            # Pre-computed costs — frontend reads these directly, no recalculation needed
            _price_in, _price_out = self._get_llm_pricing()
            _fs_cost = (
                agent_state.get("file_selection_input_tokens", 0) / 1_000_000 * _price_in
                + agent_state.get("file_selection_output_tokens", 0) / 1_000_000 * _price_out
            )
            _orch_cost = (
                agent_state.get("cumulative_input_tokens", 0) / 1_000_000 * _price_in
                + agent_state.get("cumulative_output_tokens", 0) / 1_000_000 * _price_out
            )
            session["results"]["file_selection_cost_usd"] = _fs_cost
            session["results"]["orchestrator_cost_usd"] = _orch_cost
            session["results"]["total_cost_usd"] = _fs_cost + _orch_cost + agent_state.get("rca_cost_usd", 0.0)
            try:
                stage_costs = session["results"].get("rca_costs_per_stage") or {}
                tier1_stage = stage_costs.get("Tier1")
                if isinstance(tier1_stage, dict):
                    tier1_stage["orchestrator_cost_usd"] = _orch_cost
                    tier1_stage["file_selection_cost_usd"] = _fs_cost
                    stage_costs["Tier1"] = tier1_stage
                    session["results"]["rca_costs_per_stage"] = stage_costs
            except Exception:
                pass
            session["status"] = "rca_completed"
            self.update_session(session_id, {})

        self.status = AgentStatus.COMPLETED

        # --- Return format expected by chat_ui.py ---
        total_input_bytes = total_yaml_bytes + total_log_bytes
        return {
            "session_id": session_id,
            "status": "completed",
            "need_rca_feedback": True,
            "rca_summary": report_with_user_query,
            "rca_priority_stage": rca_priority_stage,
            "has_more_priorities": has_more_priorities,
            "total_yaml_bytes": total_yaml_bytes,
            "total_log_bytes": total_log_bytes,
            "payload_bytes": payload_bytes,
            "compression_ratio": (total_input_bytes / payload_bytes) if payload_bytes else 0,
        }

    def _build_graceful_exit(
        self,
        session_id: str,
        agent_state: Dict,
        context: Dict,
        progress_callback,
    ) -> Dict:
        """
        Max iterations reached — return whatever partial RCA exists.
        Reuses _build_final_report with the last available RCA text.
        """
        rca_text = agent_state.get("rca_text", "")
        if not rca_text:
            rca_text = (
                "## Analysis Incomplete\n\n"
                "The agent reached the maximum iteration limit before completing "
                "the full analysis.\n\n"
                f"- Iterations used: {agent_state.get('iteration_count', 0)}\n"
                f"- Files analyzed: {len(agent_state.get('files_analyzed', []))}\n"
                f"- Priority stage reached: {agent_state.get('rca_priority_stage', 'unknown')}\n"
            )

        synthetic_response = {
            "stop_reason": "end_turn",
            "content": [{"type": "text", "text": rca_text}],
            "text_blocks": [{"type": "text", "text": rca_text}],
            "tool_use_blocks": [],
            "usage": {"input_tokens": 0, "output_tokens": 0},
        }
        return self._build_final_report(
            synthetic_response, session_id, agent_state, context, progress_callback,
        )

    # ==================================================================
    #  continue_rca_with_feedback — UNCHANGED
    #  (chat_ui.py "RCA satisfactory" / "RCA not satisfactory" buttons)
    # ==================================================================

    def _feedback_implies_reselect(self, feedback_text: str) -> bool:
        """True when user feedback suggests the prior hypothesis/file set was wrong."""
        if not feedback_text or not str(feedback_text).strip():
            return False
        t = str(feedback_text).lower()
        triggers = (
            "dns", "external dns", "api resolution", "missing record", "missing dns",
            "wrong root cause", "not ovn", "not crio", "not etcd", "not the root",
            "incorrect", "inaccurate", "infrastructure", "vip", "api-int",
            "hostname", "nxdomain", "no such host", "proxy", "trust bundle",
            "additionaltrustbundle", "misidentified", "actual root cause",
            "real root cause", "actual cause",
        )
        return any(x in t for x in triggers)

    def continue_rca_with_feedback(
        self,
        session_id: str,
        satisfactory: bool,
        must_gather_base_dir: str = None,
        progress_callback=None,
        feedback_text: str = "",
    ) -> Dict:
        """
        Called when the user indicates RCA is satisfactory or not.
        - If satisfactory: mark session done and return { status: 'completed', satisfactory: True }.
        - If not satisfactory: add next priority (medium then low), run analysis on new files only,
          merge with existing ML/log results, call LLM for updated RCA, return need_rca_feedback and new rca_summary.
        """
        # Re-read memory from disk each time so we always have the latest committed
        # state from the just-completed pass.  The OrchestratorAgent is created in
        # the HTTP handler thread while continue_rca_with_feedback runs in the
        # background deepening thread; re-reading here bridges any staleness gap.
        self.load_memory()
        session = self.get_session(session_id)
        if not session:
            existing = [s.get("session_id") for s in self.memory.get("sessions", [])]
            print(f"[Orchestrator] Session '{session_id}' not found. "
                  f"Available sessions: {existing}")
            return {"status": "error", "error": "Session not found.", "need_rca_feedback": False}
        self.current_session_id = session_id
        self.current_problem_statement = session.get("problem_statement", "")

        if satisfactory:
            session["status"] = "rca_satisfactory"
            self.update_session(session_id, {})
            return {"status": "completed", "satisfactory": True, "need_rca_feedback": False}

        results = session.get("results", {})
        rca_priority_stage = results.get("rca_priority_stage", "all")
        files_by_priority_paths = results.get("files_by_priority_paths") or {}
        base_dir = must_gather_base_dir or results.get("must_gather_base_dir") or ""
        previous_rca = (results.get("rca_summary") or "").strip()
        previous_ml = dict(results.get("ml_classification_result") or {})
        previous_log_entries = list(results.get("log_error_entries") or [])

        MAX_FILES_CONTINUE = 20  # cap per round to avoid LLM context overflow
        next_paths = []
        new_priority_stage = ""
        reselect_used = False

        # When feedback implies a wrong hypothesis (e.g. external DNS), re-run
        # file selection and prefer newly suggested HIGH/MEDIUM paths over
        # merely deepening the prior OVN/CRI-O-centric list.
        if self._feedback_implies_reselect(feedback_text) and base_dir:
            try:
                docs_dir = (
                    results.get("must_gather_docs_dir")
                    or getattr(self, "_last_must_gather_docs_dir", None)
                )
                if not docs_dir:
                    from must_gather_file_selector import MUST_GATHER_DOCS_DIR_DEFAULT
                    docs_dir = MUST_GATHER_DOCS_DIR_DEFAULT
                selector = self.must_gather_selector or MustGatherFileSelector(
                    config_path=self.config_path
                )
                augmented_problem = (
                    f"{self.current_problem_statement}\n\n"
                    f"USER FEEDBACK ON PRIOR RCA (re-evaluate hypotheses; prior RCA may be wrong):\n"
                    f"{feedback_text.strip()}\n\n"
                    f"PRIOR RCA SUMMARY (do not assume correct):\n"
                    f"{(previous_rca or '')[:2000]}"
                )
                suggestion = selector.suggest_files(augmented_problem, docs_dir)
                already = set()
                for bucket in ("high", "medium", "low"):
                    for p in (files_by_priority_paths.get(bucket) or []):
                        already.add(str(p).strip())
                for p in (results.get("files_analyzed") or []):
                    already.add(str(p).strip())
                extra_paths = []
                for item in (suggestion.get("suggested_files") or []):
                    if not isinstance(item, dict):
                        continue
                    p = (item.get("path") or "").strip()
                    pri = (item.get("priority") or "high").lower()
                    if p and p not in already and pri in ("high", "medium"):
                        extra_paths.append(p)
                        already.add(p)
                if extra_paths:
                    next_paths = extra_paths[:MAX_FILES_CONTINUE]
                    new_priority_stage = "reselect"
                    reselect_used = True
                    # Merge into medium bucket so later deepen still sees them
                    med = list(files_by_priority_paths.get("medium") or [])
                    for p in extra_paths:
                        if p not in med:
                            med.append(p)
                    files_by_priority_paths["medium"] = med
                    results["files_by_priority_paths"] = files_by_priority_paths
                    print(f"[Orchestrator] Re-select on feedback added {len(next_paths)} new paths")
            except Exception as e:
                print(f"[Orchestrator] re-select on feedback failed: {e}")
                traceback.print_exc()

        if not next_paths:
            if rca_priority_stage == "high" and (files_by_priority_paths.get("medium") or files_by_priority_paths.get("low")):
                next_paths = list(files_by_priority_paths.get("medium") or [])[:MAX_FILES_CONTINUE]
                if not next_paths:
                    next_paths = list(files_by_priority_paths.get("low") or [])[:MAX_FILES_CONTINUE]
                    new_priority_stage = "low"
                else:
                    new_priority_stage = "medium"
            elif rca_priority_stage in ("high_medium", "reselect") and files_by_priority_paths.get("low"):
                next_paths = list(files_by_priority_paths.get("low") or [])[:MAX_FILES_CONTINUE]
                new_priority_stage = "low"
            else:
                session["status"] = "rca_completed"
                self.update_session(session_id, {})
                return {
                    "status": "completed",
                    "satisfactory": False,
                    "need_rca_feedback": False,
                    "message": "No further priority files to add. Current RCA is based on all available files.",
                    "rca_summary": previous_rca,
                }

        if not next_paths:
            session["status"] = "rca_completed"
            self.update_session(session_id, {})
            return {"status": "completed", "satisfactory": False, "need_rca_feedback": False,
                    "message": "No additional files for this priority.", "rca_summary": previous_rca}

        _report = lambda step, msg, data=None: progress_callback(step, msg, data) if progress_callback else None
        if self.data_analyzer is None:
            try:
                self.data_analyzer = DataAnalyzer()
            except Exception as e:
                return {"status": "error", "error": str(e), "need_rca_feedback": False}
        if base_dir:
            self.data_analyzer.must_gather_base_dir = base_dir

        _report("rca_continue", "Adding {} priority files and re-running RCA...".format(new_priority_stage),
                {"new_priority": new_priority_stage, "file_count": len(next_paths),
                 "reselect_on_feedback": reselect_used})
        _report("terminal_block", "", {
            "lines": ["=" * 80,
                      "Phase 1: Selecting the Probable and available files for Issue analysis",
                      "=" * 80]
        })
        _report(
            "files_identified_intent",
            "Intent: Add next-priority files and re-run analysis.",
            None,
        )
        _report("files_identified",
                "Shortlisted files for analysis based on the user presented issue",
                {"files": next_paths})
        _report("files_by_priority",
                f"Files by priority (deepening run uses {new_priority_stage})", {
                    "high": files_by_priority_paths.get("high", []),
                    "medium": files_by_priority_paths.get("medium", []),
                    "low": files_by_priority_paths.get("low", []),
                    "first_run_paths": next_paths,
                    "rca_priority_stage": new_priority_stage,
                })
        _report("terminal_block", "", {
            "lines": ["=" * 80,
                      f"Phase 2: Selected YAML files processing ({new_priority_stage} priority)",
                      "=" * 80]
        })
        data_analysis_result = self.data_analyzer.analyze_files(
            next_paths, file_types=["yaml", "log"],
            progress_callback=progress_callback, suggested_files_with_priority=None,
        )
        raw_new_ml = data_analysis_result.get("ml_classification_result") or {}
        new_ml = raw_new_ml.get("files", {}) if isinstance(raw_new_ml, dict) and "files" in raw_new_ml else raw_new_ml

        new_total_yaml_bytes = data_analysis_result.get("total_yaml_bytes", 0)
        new_yaml_file_sizes = data_analysis_result.get("yaml_file_sizes", {})
        new_classification_table = data_analysis_result.get("classification_table") or []

        log_result = data_analysis_result.get("log_processing_result") or {}
        _error_levels = {"RareError", "HighFreqError", "Error"}
        new_log_entries_only = []
        new_log_bytes = 0
        for pf in log_result.get("per_file", []):
            source_path = pf.get("file", "")
            try:
                orig_size = os.path.getsize(source_path) if source_path and os.path.exists(source_path) else 0
            except Exception:
                orig_size = 0
            new_log_bytes += orig_size
            for level_name, path in (pf.get("saved") or {}).items():
                if level_name not in _error_levels or not path:
                    continue
                try:
                    with open(path, "r", encoding="utf-8", errors="ignore") as f:
                        content = f.read()
                    new_log_entries_only.append({
                        "file": os.path.basename(path), "content": content, "original_size": orig_size,
                    })
                except Exception:
                    pass

        _report("data_analysis_done", "YAML processing complete", {
            "classification_table": new_classification_table,
            "total_yaml_bytes": new_total_yaml_bytes,
            "summary": {
                "files_processed": data_analysis_result.get("files_processed", 0),
                "critical_fields_extracted": data_analysis_result.get("total_objects", 0),
            },
            "files_with_no_output": data_analysis_result.get("files_with_no_output", []),
        })

        _report("phase4_aggregation",
                f"Phase 4: Aggregating {new_priority_stage} priority data for deepening RCA...", None)
        _report("terminal_block", "", {
            "lines": ["=" * 80, "Phase 4: Aggregating YAML and log data for RCA payload", "=" * 80]
        })
        _report("terminal_block", "", {
            "lines": ["=" * 80,
                      f"Phase 5: Root Cause analysis — deepening with {new_priority_stage} priority files",
                      "=" * 80]
        })
        _report(
            "llm_start_intent",
            "Intent: Synthesise YAML + log findings into the final RCA report.",
            None,
        )
        _report("llm_start", "Building final RCA report...", None)

        problem_statement = self.current_problem_statement or ""
        rca_result = run_rca_and_summary_continued(
            new_ml,
            config_path=self.config_path,
            problem_statement=problem_statement,
            log_error_entries=new_log_entries_only if new_log_entries_only else None,
            previous_rca_summary=previous_rca,
            previous_priority_stage=rca_priority_stage,
            new_priority_stage=new_priority_stage,
            user_feedback_text=feedback_text,
        )
        rca_text = rca_result.get("rca_summary", "")

        # Safety net: if no new data was available (0 files resolved), the LLM
        # returns an empty summary.  Fall back to the previous round's RCA so we
        # never overwrite the good report with an empty/header-only string.
        if not rca_text:
            print(
                f"[Orchestrator] WARNING: deepening RCA produced no output "
                f"(new_priority={new_priority_stage}, resolved_files=0). "
                "Keeping previous RCA unchanged."
            )
            rca_text = (
                "_No additional files could be resolved for the "
                f"{new_priority_stage} priority stage. "
                "The analysis below is unchanged from the previous round._\n\n"
                + (previous_rca or "")
            )

        self._generate_causal_dag_after_rca(
            rca_text,
            problem_statement,
            new_priority_stage,
            progress_callback,
        )

        user_query_block = (problem_statement or "").strip()
        report_with_user_query = (
            "User Reported Issue:\n  " + user_query_block.replace("\n", "\n  ")
            + "\n\n" + "=" * 80 + "\n\n"
        ) if user_query_block else ""
        report_with_user_query += rca_text

        next_stage = "high_medium" if new_priority_stage in ("medium", "reselect") else "all"
        previous_ml.update(new_ml)
        merged_log_entries = list(previous_log_entries) + list(new_log_entries_only)

        # --- Cumulative totals for analytics ---
        prev_total_yaml = results.get("total_yaml_bytes", 0)
        prev_total_log = results.get("total_log_bytes", 0)
        cum_yaml_bytes = prev_total_yaml + new_total_yaml_bytes
        cum_log_bytes = prev_total_log + new_log_bytes
        payload_bytes = rca_result.get("payload_bytes", 0)

        # Merge yaml_file_sizes and classification_table
        prev_yaml_sizes = results.get("data_analysis", {}).get("yaml_file_sizes", {})
        prev_yaml_sizes.update(new_yaml_file_sizes)
        prev_class_table = results.get("data_analysis", {}).get("classification_table", []) or []
        merged_class_table = prev_class_table + new_classification_table

        # --- Capture individual (non-cumulative) pass cost BEFORE session update ---
        # rca_result here contains ONLY this pass's tokens/cost, not cumulative.
        stage_key = _STAGE_FILE_KEY.get(new_priority_stage, new_priority_stage.capitalize())
        per_stage = dict(results.get("rca_costs_per_stage") or {})
        price_in, price_out = self._get_llm_pricing()

        # Compute stage-level delta for orchestrator/file-selection from cumulative snapshots.
        # This keeps stage tables consistent even if future deepening adds orchestration calls.
        current_orch_in = results.get("agent_input_tokens", results.get("agent_total_tokens", 0)) or 0
        current_orch_out = results.get("agent_output_tokens", 0) or 0
        current_fs_in = results.get("file_suggestions", {}).get("input_tokens", 0) or 0
        current_fs_out = results.get("file_suggestions", {}).get("output_tokens", 0) or 0

        prev_stage_key = "Tier1" if stage_key == "Tier2" else "Tier2"
        prev_stage = per_stage.get(prev_stage_key, {}) if isinstance(per_stage.get(prev_stage_key, {}), dict) else {}

        prev_orch_cum_in = prev_stage.get("orchestrator_cum_input_tokens", current_orch_in)
        prev_orch_cum_out = prev_stage.get("orchestrator_cum_output_tokens", current_orch_out)
        prev_fs_cum_in = prev_stage.get("file_selection_cum_input_tokens", current_fs_in)
        prev_fs_cum_out = prev_stage.get("file_selection_cum_output_tokens", current_fs_out)

        orch_delta_in = max(0, current_orch_in - prev_orch_cum_in)
        orch_delta_out = max(0, current_orch_out - prev_orch_cum_out)
        fs_delta_in = max(0, current_fs_in - prev_fs_cum_in)
        fs_delta_out = max(0, current_fs_out - prev_fs_cum_out)

        orch_delta_cost = (orch_delta_in / 1_000_000 * price_in) + (orch_delta_out / 1_000_000 * price_out)
        fs_delta_cost = (fs_delta_in / 1_000_000 * price_in) + (fs_delta_out / 1_000_000 * price_out)

        per_stage[stage_key] = {
            "input_tokens": rca_result.get("input_tokens", 0),
            "output_tokens": rca_result.get("output_tokens", 0),
            "cost_usd": rca_result.get("cost_usd", 0.0),
            "payload_bytes": rca_result.get("payload_bytes", 0),
            # Stage-only shortlisted sizes (non-cumulative for Medium/Low views)
            "shortlisted_yaml_bytes": new_total_yaml_bytes,
            "shortlisted_log_bytes": new_log_bytes,
            "shortlisted_total_bytes": new_total_yaml_bytes + new_log_bytes,
            "orchestrator_input_tokens": orch_delta_in,
            "orchestrator_output_tokens": orch_delta_out,
            "orchestrator_cost_usd": orch_delta_cost,
            "file_selection_input_tokens": fs_delta_in,
            "file_selection_output_tokens": fs_delta_out,
            "file_selection_cost_usd": fs_delta_cost,
            # Internal snapshots for next-stage delta computation
            "orchestrator_cum_input_tokens": current_orch_in,
            "orchestrator_cum_output_tokens": current_orch_out,
            "file_selection_cum_input_tokens": current_fs_in,
            "file_selection_cum_output_tokens": current_fs_out,
        }

        # --- Compute cumulative RCA token/cost totals BEFORE session update ---
        # results is a live reference to session["results"], so prev_rca_result
        # MUST be read now — after the session update it would reflect current-pass
        # values and double-count them.
        prev_rca_result = results.get("rca_result", {})
        cum_rca_in = prev_rca_result.get("input_tokens", 0) + rca_result.get("input_tokens", 0)
        cum_rca_out = prev_rca_result.get("output_tokens", 0) + rca_result.get("output_tokens", 0)
        cum_rca_cost = prev_rca_result.get("cost_usd", 0.0) + rca_result.get("cost_usd", 0.0)

        # --- Persist in session (analytics reads these) ---
        session["results"]["rca_summary"] = report_with_user_query
        # Store cumulative token totals so the next deepening pass can add on top.
        session["results"]["rca_result"] = {
            "rca_summary": rca_text,
            "input_tokens": cum_rca_in,
            "output_tokens": cum_rca_out,
            "cost_usd": cum_rca_cost,
            "payload_bytes": payload_bytes,
        }
        # Persist per-stage individual costs captured before cumulative update
        session["results"]["rca_costs_per_stage"] = per_stage
        # Update total cost to reflect new cumulative RCA cost (file_selection and orchestrator unchanged)
        session["results"]["total_cost_usd"] = (
            results.get("file_selection_cost_usd", 0.0)
            + results.get("orchestrator_cost_usd", 0.0)
            + cum_rca_cost
        )
        session["results"]["ml_classification_result"] = previous_ml
        session["results"]["log_error_entries"] = merged_log_entries
        session["results"]["rca_priority_stage"] = next_stage
        session["results"]["chronology"] = rca_result.get("chronology", [])
        session["results"]["total_yaml_bytes"] = cum_yaml_bytes
        session["results"]["total_log_bytes"] = cum_log_bytes

        # Update data_analysis so analytics charts reflect all iterations
        if "data_analysis" not in session["results"]:
            session["results"]["data_analysis"] = {}
        session["results"]["data_analysis"]["classification_table"] = merged_class_table
        session["results"]["data_analysis"]["yaml_file_sizes"] = prev_yaml_sizes
        session["results"]["data_analysis"]["total_yaml_bytes"] = cum_yaml_bytes

        session["status"] = "rca_completed"
        self.update_session(session_id, {})

        compression_entries = []
        for file_name, objects in previous_ml.items():
            orig = prev_yaml_sizes.get(file_name, 0)
            pl = len(json.dumps(objects, default=str).encode("utf-8"))
            compression_entries.append({
                "file": file_name, "type": "yaml",
                "original_bytes": orig, "payload_bytes": pl,
            })
        for e in merged_log_entries:
            orig = e.get("original_size", 0)
            pl = len((e.get("content") or "").encode("utf-8"))
            compression_entries.append({
                "file": e.get("file", ""), "type": "log",
                "original_bytes": orig, "payload_bytes": pl,
            })

        cost_table_str = self._build_llm_cost_table(
            results.get("file_suggestions", {}).get("input_tokens", 0),
            results.get("file_suggestions", {}).get("output_tokens", 0),
            cum_rca_in,
            cum_rca_out,
            cum_rca_cost,
            cum_yaml_bytes,
            total_log_bytes=cum_log_bytes,
            payload_bytes=payload_bytes,
            orchestrator_input_tokens=results.get("agent_input_tokens", results.get("agent_total_tokens", 0)),
            orchestrator_output_tokens=results.get("agent_output_tokens", 0),
            orchestrator_iterations=results.get("agent_iteration_count", 0),
            compression_entries=compression_entries if compression_entries else None,
        )

        if not self._load_quiet():
            print(cost_table_str)

        # --- Write continued RCA to files ---
        try:
            results_dir = get_results_dir()
            rca_doc_path = results_dir / "rca_summary.txt"

            stage_str = _STAGE_FILE_KEY.get(new_priority_stage, new_priority_stage.capitalize())
            stage_doc_path = results_dir / f"RCA_{stage_str}.txt"

            stage_display = _STAGE_DISPLAY.get(new_priority_stage, stage_str)
            master_content = f"ROOT CAUSE ANALYSIS REPORT (CONTINUED - {stage_display})\n" + "=" * 80 + "\n\n"
            if user_query_block:
                master_content += "User Reported Issue:\n  " + user_query_block.replace("\n", "\n  ") + "\n\n" + "=" * 80 + "\n\n"
            master_content += rca_text + "\n\n" + cost_table_str + "\n"

            # Stage file contains clean markdown only (no === decorations) for the UI
            stage_content = rca_text + "\n\n" + cost_table_str + "\n"

            with open(rca_doc_path, 'w', encoding='utf-8') as f:
                f.write(master_content)
            with open(stage_doc_path, 'w', encoding='utf-8') as f:
                f.write(stage_content)

            if not self._load_quiet():
                print(f"\n[Orchestrator] Updated Master RCA written to: {rca_doc_path.name}")
                print(f"[Orchestrator] Stage-specific RCA written to: {stage_doc_path.name}")

            # Generate a short executive summary for the RCA Report page (overwrites previous)
            try:
                exec_summary = generate_rca_pass_summary(
                    rca_text, problem_statement, self.config_path,
                )
                if exec_summary:
                    summary_path = results_dir / "rca_report_summary.txt"
                    summary_path.write_text(exec_summary, encoding="utf-8")
                    if not self._load_quiet():
                        print(f"[Orchestrator] RCA report summary written to: {summary_path.name}")
            except Exception as _se:
                print(f"[Orchestrator] Warning: Could not generate executive summary: {_se}")
        except Exception as e:
            print(f"[Orchestrator] Warning: Could not write continued RCA files: {e}")

        has_more = next_stage == "high_medium" and (files_by_priority_paths.get("low")) or False
        _report("llm_done", "RCA updated with {} priority data.".format(new_priority_stage),
                {"rca_summary": report_with_user_query})
        if progress_callback:
            progress_callback("phase6_cost", "Phase 6: Cost Calculation",
                              {"cost_table": cost_table_str})
        return {
            "session_id": session_id,
            "status": "completed",
            "need_rca_feedback": True,
            "rca_summary": report_with_user_query,
            "rca_priority_stage": next_stage,
            "has_more_priorities": has_more,
            "satisfactory": False,
        }

    # ------------------------------------------------------------------
    # Status / history (unchanged)
    # ------------------------------------------------------------------

    def get_status(self) -> Dict:
        return {
            'status': self.status.value,
            'current_session_id': self.current_session_id,
            'total_sessions': self.memory['metadata']['total_sessions'],
            'last_updated': self.memory['metadata']['last_updated']
        }

    def get_history(self, limit: int = 10) -> List[Dict]:
        sessions = self.memory['sessions'][-limit:]
        return [{
            'session_id': s['session_id'],
            'problem_statement': s['problem_statement'][:100] + '...' if len(s['problem_statement']) > 100 else s['problem_statement'],
            'status': s['status'],
            'created_at': s['created_at']
        } for s in reversed(sessions)]

    def reset(self):
        self.status = AgentStatus.IDLE
        self.current_session_id = None
        self.current_problem_statement = None
        print("[Orchestrator] Agent reset to idle state")


