def main():
    print("=" * 100)
    print("MASTER ORCHESTRATOR AGENT — ReAct Loop")
    print("=" * 100)
    print("\nThis agent coordinates tools to analyze OpenShift issue problem statements.\n")

    orchestrator = OrchestratorAgent()
    problem_statement = "container image garbage collection is failing to function as expected"
    from must_gather_file_selector import MUST_GATHER_DOCS_DIR_DEFAULT
    must_gather_docs_dir = MUST_GATHER_DOCS_DIR_DEFAULT

    # Read must_gather_base_dir from config.json
    try:
        cfg = load_llm_config(str(get_config_path()))
        must_gather_base_dir = (cfg.get("must_gather_base_dir") or "").strip()
    except Exception:
        must_gather_base_dir = ""

    # Resolve relative paths against project root
    if must_gather_base_dir and not os.path.isabs(must_gather_base_dir):
        project_root = str(Path(__file__).resolve().parent.parent)
        must_gather_base_dir = os.path.join(project_root, must_gather_base_dir)

    if not must_gather_base_dir or not os.path.isdir(must_gather_base_dir):
        print(f"Must-gather base directory does not exist: {must_gather_base_dir!r}")
        print("Set 'must_gather_base_dir' in Config/config.json to the path of your must-gather data folder.")
        return

    print(f"Problem Statement: {problem_statement.strip()}")
    print(f"Must-gather docs directory: {must_gather_docs_dir}")
    print(f"Must-gather base directory: {must_gather_base_dir}\n")
    print("[Orchestrator] Starting agentic workflow...")

    workflow_result = orchestrator.execute_workflow(
        problem_statement,
        must_gather_docs_dir,
        must_gather_base_dir=must_gather_base_dir,
    )

    if workflow_result.get('status') == 'error':
        print(f"\nError: {workflow_result.get('error', 'Unknown error')}")
    else:
        print(f"\nWorkflow completed. Session: {workflow_result.get('session_id')}")
        print(f"Priority stage: {workflow_result.get('rca_priority_stage')}")
        print(f"Has more priorities: {workflow_result.get('has_more_priorities')}")


if __name__ == "__main__":
    main()
