    def _get_llm_pricing(self) -> tuple:
        """Return (price_per_1m_input, price_per_1m_output) from config (USD)."""
        try:
            path = Path(self.config_path)
            if path.exists():
                with open(path, 'r', encoding='utf-8') as f:
                    cfg = json.load(f)
                claude = cfg.get('claude', {})
                return (
                    float(claude.get('price_per_1m_input_tokens', 3.0)),
                    float(claude.get('price_per_1m_output_tokens', 15.0)),
                )
        except Exception:
            pass
        return (3.0, 15.0)

    def _build_llm_cost_table(
        self,
        file_selection_input_tokens: int,
        file_selection_output_tokens: int,
        rca_input_tokens: int,
        rca_output_tokens: int,
        rca_cost_usd: float,
        total_yaml_bytes: int,
        total_log_bytes: int = 0,
        payload_bytes: int = 0,
        compression_entries: Optional[List[Dict[str, Any]]] = None,
        orchestrator_input_tokens: int = 0,
        orchestrator_output_tokens: int = 0,
        orchestrator_iterations: int = 0,
    ) -> str:
        """Build token/cost table for all phases."""
        price_in, price_out = self._get_llm_pricing()
        fs_cost = (file_selection_input_tokens / 1_000_000 * price_in) + (file_selection_output_tokens / 1_000_000 * price_out)
        orch_cost = (orchestrator_input_tokens / 1_000_000 * price_in) + (orchestrator_output_tokens / 1_000_000 * price_out)
        total_with_ml = fs_cost + orch_cost + rca_cost_usd
        total_input_bytes = total_yaml_bytes + total_log_bytes

        def cost_fmt(x: float, blank_zero: bool = False) -> str:
            if blank_zero and x == 0:
                return "—"
            return f"${x:>11.6f}"

        def tok(t: int) -> str:
            return f"{t:,}" if t is not None and t > 0 else "—"

        sep = "-" * 100
        lines = [
            "",
            "=" * 100,
            "LLM API TOKEN & COST SUMMARY — ALL PHASES",
            "=" * 100,
            "  Phase 1: Selecting probable/available files   Phase 2: YAML processing   Phase 3: Log processing",
            "  Phase 4: Data aggregation (YAML+LOG)   Phase 5: Root Cause analysis   Phase 6: Cost Calculation",
            "",
            "  WITH ML EXTRACTION (current run)",
            sep,
            f"  {'Phase':<32} {'Input tokens':>14} {'Output tokens':>14} {'Cost (USD)':>14}",
            f"  {'0. Orchestrator ReAct loop':<32} {tok(orchestrator_input_tokens):>14} {tok(orchestrator_output_tokens):>14} {cost_fmt(orch_cost):>14}",
            f"     ({orchestrator_iterations} iterations)" if orchestrator_iterations else "",
            f"  {'1. File selection':<32} {tok(file_selection_input_tokens):>14} {tok(file_selection_output_tokens):>14} {cost_fmt(fs_cost, blank_zero=True):>14}",
            f"  {'2. YAML processing (local ML)':<32} {'—':>14} {'—':>14} {'—':>14}",
            f"  {'3. Log processing (local Drain3)':<32} {'—':>14} {'—':>14} {'—':>14}",
            f"  {'4. Data aggregation (no LLM)':<32} {'—':>14} {'—':>14} {'—':>14}",
            f"  {'5. RCA (extracted payload)':<32} {tok(rca_input_tokens):>14} {tok(rca_output_tokens):>14} {cost_fmt(rca_cost_usd):>14}",
            f"  {'Total':<32} {'':>14} {'':>14} {cost_fmt(total_with_ml):>14}",
            "",
            "  COMPRESSION RATIO (input size vs payload sent to LLM)",
            sep,
        ]
        if total_input_bytes and payload_bytes:
            overall_ratio = total_input_bytes / payload_bytes
            lines.append(f"  Total input (YAML + logs): {total_input_bytes:,} bytes  →  Payload to LLM: {payload_bytes:,} bytes")
            lines.append(f"  Overall compression ratio: {overall_ratio:.2f}x")
        lines.append("")
        if compression_entries:
            lines.append(f"  {'File':<50} {'Type':<6} {'Original (B)':>14} {'Payload (B)':>14} {'Ratio':>10}")
            lines.append(sep)
            for e in compression_entries:
                fname = (e.get("file") or "")[:48]
                typ = (e.get("type") or "—")[:6]
                orig = e.get("original_bytes", 0)
                pl = e.get("payload_bytes", 0)
                ratio = (orig / pl) if pl else 0
                lines.append(f"  {fname:<50} {typ:<6} {orig:>14,} {pl:>14,} {ratio:>10.2f}x")
            lines.append("")
        lines.append("=" * 100)
        return "\n".join(lines)

