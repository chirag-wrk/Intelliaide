    def _redistribute_priorities(self, by_priority: Dict[str, List[str]]) -> Dict[str, List[str]]:
        """
        If select_files returned all files at the same priority, redistribute
        them into high (2/3), medium (1/6), low (1/6) so incremental deepening
        has meaningful tiers to expand through.
        """
        high = list(by_priority.get("high", []))
        medium = list(by_priority.get("medium", []))
        low = list(by_priority.get("low", []))

        populated = [(k, v) for k, v in [("high", high), ("medium", medium), ("low", low)] if v]
        if len(populated) == 1 and len(populated[0][1]) > 1:
            all_files = populated[0][1]
            n = len(all_files)
            high_count = max(1, n * 2 // 3)
            rest = n - high_count
            med_count = rest // 2
            high = all_files[:high_count]
            medium = all_files[high_count:high_count + med_count]
            low = all_files[high_count + med_count:]

        return {"high": high, "medium": medium, "low": low}

    def _update_analyzed_tiers(self, agent_state: Dict, newly_analyzed_files: List[str]):
        """
        Update rca_priority_stage based on which priority tiers' files have
        been fed into analyze_yaml / analyze_logs so far.
        """
        fbp = agent_state.get("files_by_priority", {})
        analyzed = set(agent_state.get("files_analyzed", []))

        high_files = set(fbp.get("high", []))
        medium_files = set(fbp.get("medium", []))
        low_files = set(fbp.get("low", []))

        high_covered = bool(high_files and (high_files & analyzed))
        medium_covered = bool(medium_files and (medium_files & analyzed))
        low_covered = bool(low_files and (low_files & analyzed))

        if high_covered and medium_covered and low_covered:
            agent_state["rca_priority_stage"] = "all"
        elif high_covered and medium_covered:
            agent_state["rca_priority_stage"] = "high_medium"
        elif high_covered:
            agent_state["rca_priority_stage"] = "high"
        elif medium_covered:
            agent_state["rca_priority_stage"] = "medium"
        # else: keep whatever it was (defaults to "high")

