class OrchestratorAgent:
    """
    Master orchestrator agent that uses a ReAct (Reasoning + Acting) loop to
    coordinate tools and produce root cause analysis reports.

    Public interface consumed by chat_ui.py:
      - OrchestratorAgent(config_path, memory_file)
      - execute_workflow(problem_statement, must_gather_docs_dir,
                         must_gather_base_dir, progress_callback) -> Dict
      - continue_rca_with_feedback(session_id, satisfactory,
                                   must_gather_base_dir, progress_callback) -> Dict
    """

    def __init__(self, config_path: str = None, memory_file: str = None, reset: bool = True):
        self.config_path = config_path or str(get_config_path())
        self.memory_file = memory_file or str(get_memory_file_path())
        self.status = AgentStatus.IDLE
        self.current_session_id = None
        self.current_problem_statement = None
        self.memory = {
            'sessions': [],
            'problem_statements': [],
            'file_suggestions': [],
            'sub_agent_results': {},
            'metadata': {
                'created_at': datetime.datetime.now().isoformat(),
                'last_updated': datetime.datetime.now().isoformat(),
                'total_sessions': 0
            }
        }
        self.must_gather_selector = None
        self.data_analyzer = None
        self.root_cause_analyzer = None
        self.current_workflow_step = None
        self.workflow_status = {}

        # Agent-level configuration
        self.max_iterations = 25
        self.max_deepening_rounds = 3
        self._load_agent_config()

        if reset:
            self.reset_memory()
        else:
            self.load_memory()
        self._initialize_sub_agents()

    # ------------------------------------------------------------------
    # Configuration
    # ------------------------------------------------------------------

    def _load_agent_config(self):
        """Load agent-specific config fields (max_iterations, etc.)."""
        try:
            cfg = load_llm_config(self.config_path)
            agent_cfg = cfg.get("agent", {})
            self.max_iterations = int(agent_cfg.get("max_iterations", 25))
            self.max_deepening_rounds = int(agent_cfg.get("max_deepening_rounds", 3))
        except Exception:
            pass

    def _initialize_sub_agents(self):
        """Initialize each sub-agent in its own try so one failure does not block the others."""
        try:
            self.must_gather_selector = MustGatherFileSelector(config_path=self.config_path)
            print("[Orchestrator] Must-gather file selector initialized")
        except Exception as e:
            print(f"[Orchestrator] Warning: Failed to initialize file selector: {e}")
            traceback.print_exc()
            self.must_gather_selector = None
        try:
            self.data_analyzer = DataAnalyzer()
            print("[Orchestrator] Data analyzer initialized")
        except Exception as e:
            print(f"[Orchestrator] Warning: Failed to initialize data analyzer: {e}")
            traceback.print_exc()
            self.data_analyzer = None
        try:
            self.root_cause_analyzer = RootCauseAnalyzerYAML()
            print("[Orchestrator] Root cause analyzer initialized")
        except Exception as e:
            print(f"[Orchestrator] Warning: Failed to initialize root cause analyzer: {e}")
            traceback.print_exc()
            self.root_cause_analyzer = None
        if self.must_gather_selector or self.data_analyzer or self.root_cause_analyzer:
            print("[Orchestrator] Sub-agents ready (some may be missing if init failed).")

    def _load_quiet(self) -> bool:
        """If True, suppress most prints."""
        try:
            path = Path(self.config_path)
            if path.exists():
                with open(path, 'r', encoding='utf-8') as f:
                    cfg = json.load(f)
                return cfg.get('quiet', False)
        except Exception:
            pass
        return False

    # ------------------------------------------------------------------
    # Memory / session management  (unchanged — chat_ui + continue_rca depend on these)
    # ------------------------------------------------------------------

    def load_memory(self):
        """Load memory from file (used by continue_rca_with_feedback to resume)."""
        if os.path.exists(self.memory_file):
            try:
                with open(self.memory_file, 'r', encoding='utf-8') as f:
                    self.memory = json.load(f)
                print(f"[Orchestrator] Memory loaded from {self.memory_file}")
            except Exception as e:
                print(f"[Orchestrator] Warning: Failed to load memory: {e}")
        else:
            print(f"[Orchestrator] No existing memory file found. Starting fresh.")

    def reset_memory(self):
        """Overwrite agent_memory.json with a fresh state. Called at startup."""
        self.memory = {
            'sessions': [],
            'problem_statements': [],
            'file_suggestions': [],
            'sub_agent_results': {},
            'metadata': {
                'created_at': datetime.datetime.now().isoformat(),
                'last_updated': datetime.datetime.now().isoformat(),
                'total_sessions': 0
            }
        }
        self.save_memory()
        print(f"[Orchestrator] Memory reset; {self.memory_file} overwritten with fresh state.")

    def save_memory(self):
        try:
            self.memory['metadata']['last_updated'] = datetime.datetime.now().isoformat()
            with open(self.memory_file, 'w', encoding='utf-8') as f:
                json.dump(self.memory, f, indent=2, ensure_ascii=False)
        except Exception as e:
            print(f"[Orchestrator] Error: Failed to save memory: {e}")

    def create_session(self, problem_statement: str) -> str:
        session_id = f"session_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S_%f')}_{secrets.token_hex(4)}"
        session = {
            'session_id': session_id,
            'problem_statement': problem_statement,
            'status': 'created',
            'created_at': datetime.datetime.now().isoformat(),
            'updated_at': datetime.datetime.now().isoformat(),
            'results': {},
            'sub_agent_calls': [],
            'workflow_steps': [],
            'cycles': [],
            'user_responses': [],
            'report_generated': False
        }
        self.memory['sessions'].append(session)
        self.memory['problem_statements'].append({
            'session_id': session_id,
            'problem_statement': problem_statement,
            'timestamp': datetime.datetime.now().isoformat()
        })
        self.memory['metadata']['total_sessions'] = len(self.memory['sessions'])
        self.current_session_id = session_id
        self.current_problem_statement = problem_statement
        self.status = AgentStatus.PROCESSING
        self.save_memory()
        print(f"\n[Orchestrator] Created new session: {session_id}")
        return session_id

    def get_session(self, session_id: str) -> Optional[Dict]:
        for session in self.memory['sessions']:
            if session['session_id'] == session_id:
                return session
        return None

    def update_session(self, session_id: str, updates: Dict):
        session = self.get_session(session_id)
        if session:
            session.update(updates)
            session['updated_at'] = datetime.datetime.now().isoformat()
            self.save_memory()

    def _track_workflow_step(self, step_name: str, status: str, details: Dict = None):
        if not self.current_session_id:
            return
        step = {
            'step': step_name,
            'status': status,
            'timestamp': datetime.datetime.now().isoformat(),
            'details': details or {}
        }
        session = self.get_session(self.current_session_id)
        if session:
            if 'workflow_steps' not in session:
                session['workflow_steps'] = []
            session['workflow_steps'].append(step)
            self.update_session(self.current_session_id, {})

